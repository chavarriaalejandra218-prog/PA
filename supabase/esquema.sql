-- ---------------------------------------------------------
-- 1) INVENTARIO · tabla productos
-- ---------------------------------------------------------
create table if not exists public.productos (
  id           bigint generated by default as identity primary key,
  codigo       text not null unique,
  nombre       text not null,
  descripcion  text,
  categoria    text,
  precio       numeric(12, 2) not null default 0 check (precio >= 0),
  stock        integer not null default 0 check (stock >= 0),
  creado_en    timestamptz not null default now()
);

-- ---------------------------------------------------------
-- 2) PERSONAL · tabla personal
--    Identidad = clave primaria / identificador único
-- ---------------------------------------------------------
create table if not exists public.personal (
  identidad   text primary key,
  nombres     text not null,
  apellidos   text not null,
  genero      text not null check (genero in ('Femenino', 'Masculino', 'Otro')),
  telefono    text not null,
  direccion   text not null,
  correo      text,
  cargo       text,
  creado_en   timestamptz not null default now()
);

-- ---------------------------------------------------------
-- 3) PROVEEDORES · tabla proveedores
--    Código autogenerado: PRV-0001, PRV-0002, ...
-- ---------------------------------------------------------
create table if not exists public.proveedores (
  id             bigint generated by default as identity primary key,
  codigo         text unique,
  empresa        text not null,
  representante  text not null,
  encargado      text not null,
  telefono       text not null,
  direccion      text not null,
  email          text not null,
  creado_en      timestamptz not null default now()
);

-- Función + trigger que asignan el código serial del proveedor
create or replace function public.asignar_codigo_proveedor()
returns trigger
language plpgsql
as $$
begin
  if new.codigo is null or btrim(new.codigo) = '' then
    new.codigo := 'PRV-' || lpad(new.id::text, 4, '0');
  end if;
  return new;
end;
$$;

drop trigger if exists trg_codigo_proveedor on public.proveedores;

create trigger trg_codigo_proveedor
before insert on public.proveedores
for each row
execute function public.asignar_codigo_proveedor();

-- ---------------------------------------------------------
-- 4) SEGURIDAD · Row Level Security
--    Solo usuarios autenticados pueden leer y escribir.
-- ---------------------------------------------------------
alter table public.productos   enable row level security;
alter table public.personal    enable row level security;
alter table public.proveedores enable row level security;

drop policy if exists "productos_autenticados" on public.productos;
create policy "productos_autenticados"
  on public.productos for all
  to authenticated
  using (true)
  with check (true);

drop policy if exists "personal_autenticados" on public.personal;
create policy "personal_autenticados"
  on public.personal for all
  to authenticated
  using (true)
  with check (true);

drop policy if exists "proveedores_autenticados" on public.proveedores;
create policy "proveedores_autenticados"
  on public.proveedores for all
  to authenticated
  using (true)
  with check (true);

